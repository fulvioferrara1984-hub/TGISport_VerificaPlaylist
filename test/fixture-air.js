// Testi .hdm e AIR package sintetici, nello stesso formato di DBRLive Inventory Manager.

// ads: { id: [nome, nomeAdvertiser|null, file] }; intervalli: [{ inizio, durata, mappe: [[idAd, [zone…]]] }]
function hdmSequenza(intervalli, ads) {
  const adv = new Map();
  let t = '# Generated by DBRLive Inventory Manager 1.6.5\n\nsequence = 1\n{\n    name = Prova\n}\n\n';
  Object.entries(ads).forEach(([id, [nome, inserzionista]]) => {
    if (inserzionista && !adv.has(inserzionista)) adv.set(inserzionista, 9000 + adv.size);
  });
  adv.forEach((n, nome) => { t += `advertiser = ${n}\n{\n    name = ${nome}\n}\n\n`; });
  Object.entries(ads).forEach(([id, [nome, inserzionista, file]]) => {
    t += `ad = ${id}\n{\n    name = ${nome}\n` + (inserzionista ? `    advertiser = ${adv.get(inserzionista)}\n` : '') + `    file = ${file}\n    \n}\n\n`;
  });
  intervalli.forEach((iv) => {
    t += `interval = ${iv.inizio}, ${iv.durata}, Multiple\n{\n`;
    iv.mappe.forEach(([id, zone]) => { t += `    map = ${id} to ${zone.join(', ')}\n`; });
    t += '    \n}\n\n';
  });
  return t + 'threshold = 70';
}

// stream: [[nome, [[nomeSegmento, file], …]], …]
function hdmEvento({ nome = 'ALFA-BETA', data = '2026-10-12', venue = 'Stadio Prova', zone = ['FULL PERIMETER', 'CC'], stream = [] }) {
  let t = '# Generated by DBRLive Inventory Manager 1.6.5\n\nevent\n{\n  id = 1\n' + `  name = ${nome}\n  description = \n  date = ${data}\n  \n\n`;
  t += `  venue\n  {\n    #id = 1\n    name = ${venue}\n    location = Italia\n  }\n\n  zones\n  {\n`;
  zone.forEach((z, i) => { t += `    zone = ${i}\n    {\n      #id = ${i}\n      name = ${z}\n      size\n      {\n        width = 1 m\n      }\n    }\n`; });
  t += '  }\n\n  streams\n  {\n';
  stream.forEach(([s, segmenti], i) => {
    t += `    stream\n    {\n      #id = ${100 + i}\n      name = ${s}\n      type = Local\n\n      #empty\n      workstations\n      {\n      }\n\n      sequences\n      {\n`;
    segmenti.forEach(([sn, f], j) => { t += `        sequence\n        {\n          #id = ${200 + j}\n          name = ${sn}\n          file = ${f}\n        }\n`; });
    t += '        \n       \n      }\n    }\n';
  });
  return t + '  }\n  \n  \n}\n';
}

// Video mp4 minimo con la sola durata (box moov/mvhd): versione 0 o 1 del box, moov prima o dopo i dati.
function mp4(secondi, { versione = 0, moovInFondo = false, timescale = 600 } = {}) {
  const box = (tipo, ...parti) => {
    const corpo = Buffer.concat(parti.map((x) => Buffer.from(x)));
    const b = Buffer.alloc(8 + corpo.length);
    b.writeUInt32BE(b.length, 0); b.write(tipo, 4, 'latin1'); corpo.copy(b, 8);
    return b;
  };
  const d = Math.round(secondi * timescale);
  const mvhd = Buffer.alloc(versione === 1 ? 112 : 100);
  mvhd[0] = versione;
  if (versione === 1) { mvhd.writeUInt32BE(timescale, 20); mvhd.writeUInt32BE(Math.floor(d / 2 ** 32), 24); mvhd.writeUInt32BE(d % 2 ** 32, 28); }
  else { mvhd.writeUInt32BE(timescale, 12); mvhd.writeUInt32BE(d, 16); }
  const parti = [box('ftyp', Buffer.from('isom0000')), box('moov', box('mvhd', mvhd)), box('mdat', Buffer.alloc(64))];
  if (moovInFondo) parti.push(parti.splice(1, 1)[0]);
  return new Uint8Array(Buffer.concat(parti));
}

// AIR package come ArrayBuffer: { cartella, evento, sequenze: { 'sequences/x.hdm': testo }, media: [nome | [nome, byte]] }
async function zipAir(JSZip, { cartella = '20261012_alfa-beta', evento, sequenze = {}, media = [] }) {
  const z = new JSZip();
  z.file(`${cartella}/version.txt`, 'version: 2.01');
  if (evento) z.file(`${cartella}/event.hdm`, evento);
  Object.entries(sequenze).forEach(([p, t]) => z.file(`${cartella}/${p}`, t));
  media.forEach((m) => (Array.isArray(m) ? z.file(`${cartella}/advertisements/${m[0]}`, m[1]) : z.file(`${cartella}/advertisements/${m}`, new Uint8Array([1, 2, 3]))));
  return z.generateAsync({ type: 'arraybuffer' });
}

// Registra i percorsi dei file di cui si legge il contenuto (spia su ZipObject.prototype.async).
async function spiaLetture(JSZip, dati) {
  const z = await JSZip.loadAsync(dati);
  const proto = Object.getPrototypeOf(Object.values(z.files)[0]);
  const originale = proto.async;
  const letti = [];
  proto.async = function (...a) { letti.push(this.name); return originale.apply(this, a); };
  return { letti, ripristina: () => { proto.async = originale; } };
}

module.exports = { hdmSequenza, hdmEvento, mp4, zipAir, spiaLetture };
